function heroFor(slug: string, fallback: string): string {
  if (projectImages[slug]?.[0]) return projectImages[slug][0];
  const parent = parentChildMap[slug];
  if (parent && projectImages[parent]?.[0]) return projectImages[parent][0];
  return fallback;
}

function galleryFor(slug: string, fallback: string[]): string[] {
  if (projectImages[slug] && projectImages[slug].length > 0) return projectImages[slug];
  const parent = parentChildMap[slug];
  if (parent && projectImages[parent] && projectImages[parent].length > 0)
    return projectImages[parent];
  return fallback;
}

function typesFor(price: number, beach: boolean) {
  const base = beach ? ["Chalet", "Twin House", "Villa"] : ["Apartment", "Penthouse", "Villa"];
  if (price > 12) base.push("Standalone Villa");
  if (price < 9) base.push("Studio");
  return base;
}

function paymentPlan(price: number) {
  const dp = price < 10 ? 5 : 10;
  const years = price > 15 ? 9 : price > 10 ? 8 : 7;
  return `${dp}% down payment over ${years} years equal installments`;
}

